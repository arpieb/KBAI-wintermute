"""Thin wrapper around an embedded LadybugDB (Kùzu-fork) graph database."""

from __future__ import annotations

from pathlib import Path
from typing import Any

import ladybug

# LadybugDB requires a declared schema. Schema.org type ancestry is stored as a label list on
# Thing (Neo4j used multi-labels), and open-ended properties as a JSON string.
SCHEMA = [
    # FrameNet.
    "CREATE NODE TABLE IF NOT EXISTS Frame(ID INT64 PRIMARY KEY, name STRING)",
    "CREATE NODE TABLE IF NOT EXISTS FE(ID INT64 PRIMARY KEY, name STRING, abbrev STRING)",
    "CREATE NODE TABLE IF NOT EXISTS LU(ID INT64 PRIMARY KEY, name STRING, POS STRING, frameID INT64, frame STRING, status STRING)",
    "CREATE REL TABLE IF NOT EXISTS frame_element(FROM Frame TO FE, type STRING)",
    "CREATE REL TABLE IF NOT EXISTS valence_unit(FROM LU TO FE, GF STRING, PT STRING)",
    "CREATE REL TABLE IF NOT EXISTS frame_relation(FROM Frame TO Frame, type STRING)",
    # Domain knowledge.
    "CREATE NODE TABLE IF NOT EXISTS Thing(ID STRING PRIMARY KEY, name STRING, labels STRING[], props STRING)",
    "CREATE NODE TABLE IF NOT EXISTS Alias(name STRING PRIMARY KEY)",
    "CREATE REL TABLE IF NOT EXISTS alias_of(FROM Alias TO Thing)",
    "CREATE REL TABLE IF NOT EXISTS related(FROM Thing TO Thing, type STRING)",
    # Conversation state.
    "CREATE NODE TABLE IF NOT EXISTS Context(ID STRING PRIMARY KEY, config STRING)",
    "CREATE REL TABLE IF NOT EXISTS context_uses(FROM Context TO Thing)",
    # Which bulk datasets have been loaded.
    "CREATE NODE TABLE IF NOT EXISTS KBStatus(key STRING PRIMARY KEY)",
]


class Graph:
    def __init__(self, path: Path | str):
        if str(path) != ":memory:":
            Path(path).parent.mkdir(parents=True, exist_ok=True)
        self.db = ladybug.Database(str(path))
        self.conn = ladybug.Connection(self.db)
        for stmt in SCHEMA:
            self.conn.execute(stmt)

    def execute(self, query: str, params: dict[str, Any] | None = None) -> None:
        self.conn.execute(query, params or {})

    def rows(self, query: str, params: dict[str, Any] | None = None) -> list[dict[str, Any]]:
        result = self.conn.execute(query, params or {})
        return result.rows_as_dict().get_all()

    def copy_from(self, table: str, csv_path: Path) -> None:
        # COPY doesn't take parameters; the path is generated by us, never user input.
        self.conn.execute(f"COPY {table} FROM '{csv_path.as_posix()}' (header=true)")

    # Dataset load tracking (replaces the original WMKBStatus node).
    def is_loaded(self, key: str) -> bool:
        return bool(self.rows("MATCH (s:KBStatus {key: $k}) RETURN s.key", {"k": key}))

    def mark_loaded(self, key: str) -> None:
        self.execute("MERGE (s:KBStatus {key: $k})", {"k": key})

    def clear_loaded(self, key: str) -> None:
        self.execute("MATCH (s:KBStatus {key: $k}) DELETE s", {"k": key})

    def close(self) -> None:
        self.conn.close()
        self.db.close()
